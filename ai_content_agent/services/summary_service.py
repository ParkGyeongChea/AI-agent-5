"""
summary_service.py

이 파일은 영상 요약 데이터를 가져오는 서비스 레이어이다

1. video_id 기반으로 요약 데이터 조회
2. 예외를 내부에서 처리
3. 항상 동일한 Response Contract 반환
4. UI가 데이터 소스를 몰라도 되도록 추상화

왜 서비스 레이어로 분리하는가?
- UI에서 직접 mock 데이터를 import하면 나중에 API로 교체할 때 UI까지 수정해야 한다
- 서비스 레이어를 두면 데이터 소스 변경 시 이 파일만 수정하면 된다

반환 구조 (절대 변경 금지)

{
    "data": {
        "summary": str,
        "timeline": list
    } or None,

    "error": None or {
        "type": str,
        "message": str,
        "retryable": bool
    }
}

이 구조를 유지하는 이유
→ UI가 항상 동일한 방식으로 처리 가능
→ 성공/실패에 관계없이 안정적인 상태 보장
"""
# ==========================================================
# 1️⃣ 모듈 import
# ==========================================================

import time    # 처리 지연 시뮬레이션용
from mock.summary_mock import summary_mock
# summary_mock는 video_id별 요약 데이터를 담고 있는 가짜 데이터
# 실제 서비스에서는 API 요청 코드로 교체된다

# ==========================================================
# 2️⃣ 요약 데이터 요청 함수
# ==========================================================

def fetch_summary(video_id : str) :
    """
    video_id : 선택된 영상의 고유 ID
    
    왜 video_id만 받는가?
    → 최소 정보 원칙 (Minimal State Principle)
    → 서버는 ID만 필요하다
    → 객체 전체를 넘기면 결합도가 높아진다
    
    데이터 흐름
    
    video_id
        ↓
    mock 데이터 조회
        ↓
    Response Contract 형태로 반환
    
    항상 동일한 구조를 반환한다
    """
    
    try : 
        # --------------------------------------------------
        # 2-1 처리 지연 시뮬레이션 (LLM 호출 가정)
        # --------------------------------------------------
        # 실제 환경에서는
        # LLM 호출 / 외부 API 요청 / DB 조회 등이 발생
        # time.sleep은 "비동기 지연 상황"을 테스트하기 위한 것이다
        # --------------------------------------------------
        
        time.sleep(1)
        
        # --------------------------------------------------
        # 2-2 video_id 존재 여부 검사
        # --------------------------------------------------
        # video_id가 mock 데이터에 없다면 정상적인 요약을 만들 수 없다.
        # --------------------------------------------------
        
        if video_id not in summary_mock :
            
            return {
                "data" : None,  # 실패시 data는 반드시 None
                "error" : {
                    "type" : "SUMMARY_NOT_FOUND",
                    "message" : "요약 데이터를 찾을 수 없습니다",
                    "retryable" : False
                }
            }
            
        # --------------------------------------------------
        # 2-3 성공 반환 구조
        # --------------------------------------------------
        # 반드시 data와 error 키를 모두 포함해야 한다.
        # --------------------------------------------------
        
        return {
            "data" : summary_mock[video_id],
            "error" : None
        }
        
    # --------------------------------------------------
    # 2-4 예외 발생 시 처리
    # --------------------------------------------------
    # 예외를 UI로 던지지 않는다.
    # 서비스 레이어에서 흡수하고
    # 일관된 구조로 반환한다.
    # --------------------------------------------------
        
    except Exception :
        
        return {
            "data" : None,
            "error" : {
                "type" : "SUMMARY_FAILED",
                "message" : "요약 처리 중 오류가 발생했습니다",
                "retryable" : False
            }
        }