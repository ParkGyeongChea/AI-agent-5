"""
recommend_service.py 

이 파일은 추천 데이터를 가져오는 역할을 한다
→ 데이터 요청을 담당하는 레이어 (데이터 통신과 처리 담당)

이 레이어의 책임:
1. 데이터 요청 수행 (지금은 Mock)
2. 재시도 로직 처리
3. 예외를 내부에서 흡수
4. 항상 동일한 반환 구조(Response Contract) 보장

중요 개념:
- UI는 절대 예외를 직접 처리하지 않는다.
- 서비스 레이어가 예외를 흡수하고 일관된 결과 형태로 반환한다.

UI 코드와 데이터 로직을 분리하는 이유
→ 관심사 분리 (Separation of Concerns)

지금은 Mock 데이터를 반환하지만,
나중에는 실제 백엔드 API 요청으로 교체될 수 있다

즉, 이 레이어는
"데이터 가져오는 책임"을 분리한 것이다

services 레이어를 두는 이유
→ UI를 데이터 소스와 분리하기 위해
→ 추상화 + 교체 가능성 + 확장성 + 유지보수성 확보

설계하는 방법을 배울 수 있다
1. 재시도 로직(처리)
2. 에러처리
3. 일관된 반환 구조
4. UI와 완전 분리

서비스 레이어는 예외를 던지는 곳이 아니라
예외를 흡수하고 일관된 결과로 변환하는 곳이다

모든 서비스 함수는 동일한 응답 패턴을 유지해야
UI가 안정적이고 확장 가능해진다
"""
# ==========================================================
# 1️⃣ 필요한 모듈 import
# ==========================================================

import time
from mock.recommend_mock import recommend_mock

# ==========================================================
# 2️⃣ 추천 서비스 함수 정의
# ==========================================================

def fetch_recommend(query : str) :
    """
    query : 사용자가 입력한 질문 (검색어)
    
    반환 구조는 항상 동일해야 한다 
    {
        "data": {
            "videos": [...]
        } or None,

        "error": {
            "type": str,
            "message": str,
            "retryable": bool
        } or None
    }

    성공 시:
        error = None

    실패 시:
        data = None
        error = 에러 객체
    
    지금은 실제 API 호출 대신
    2초 대기 후 Mock 데이터를 반환한다
    
    실제 서비스라면
    → API 호출
    → LLM 요청
    → DB 조회
    
    time.sleep()을 사용하는 이유
    → AI 응답 지연을 시뮬레이션 하기 위함
    """
    # ------------------------------------------------------
    # 2-1 최대 재시도 횟수 설정
    # ------------------------------------------------------
    
    max_retry = 3   # 최대 재시도 횟수
    
    # ------------------------------------------------------
    # 2-2 재시도 루프
    # ------------------------------------------------------
    
    for attempt in range(max_retry) :
        try :
            # ---------------------------------------
            # 실제 서비스라면 여기서 
            # 외부 API 호출
            # LLM 호출 
            # DB 조회
            # ---------------------------------------
            
            time.sleep(1)   # AI 처리 지연 시뮬레이션
            
            # ----------------------------------------------
            # 성공 시 반환 구조
            # ----------------------------------------------
            
            return {
                "data" : 
                {"videos" : recommend_mock["videos"]},
                "error" : None
                # 에러를 항상 포함시키는 이유는 일관된 반환 구조를 위해서
                # error는 상태 + 의미 + 메시지 + 확장성까지 담을 수 있다
            }
        
        except Exception as e :
            # ----------------------------------------------
            # 마지막 시도까지 실패한 경우
            # ----------------------------------------------
            if attempt == max_retry - 1 :
                return {
                        "data" : None,
                        "error": {
                            "type" : "RECOMMEND_FAILED",
                            "message" : "추천 처리 중 오류가 발생했습니다",
                            "retryable" : False
                            }
                        }
            
            # ----------------------------------------------
            # 재시도 전 대기
            # ----------------------------------------------
            time.sleep(0.5)
    
    # time.sleep(2)   # AI가 처리 중인 것처럼 보이게
    
