"""
search.py (UI 레이어)

사용자가 학습 주제를 입력하고
추천 요청을 실행하는 UI 컴포넌트이다

컴포넌트의 역할
1. 사용자 입력 받기
2. 버튼 클릭 감지
3. 서비스 호출
4. 상태 업데이트
5. 에러 표시

중요
UI는 예외를 직접 처리하지 않는다
서비스가 반환한 구조를 그대로 소비한다

Streamlit의 Rerun 구조 + session_state 흐름을 
이해하는 핵심 단계

데이터 흐름:

사용자 입력
    ↓
버튼 클릭
    ↓
fetch_recommend() 호출
    ↓
session_state.videos 업데이트
    ↓
앱 rerun
    ↓
UI 갱신

"""

# ==========================================================
# 1️⃣ 필요한 모듈 import
# ==========================================================

import streamlit as st  # Streamlit UI 라이브러리
from services.recommend_service import fetch_recommend
# fetch_recommend는 "데이터를 가져오는 책임"을 가진 함수
# UI 코드 안에 데이터를 직접 작성하지 않는 이유는
# 관심사 분리(Separation of Concerns) 때문이다

# ==========================================================
# 2️⃣ 검색 UI 렌더링 함수 정의
# ==========================================================

def render_search() :
    """
    이 함수는 검색 UI를 화면에 그린다
    
    입력 → 버튼 → 서비스 호출 → 상태 저장
    
    중요한 점 :
    Streamlit은 버튼 클릭 시 파일 전체를 다시 실행한다 (rerun)
    따라서 상태 변화는 반드시 session_state에 저장해야 한다
    """
    
    # ------------------------------------------------------
    # 2-1 사용자 입력 받기
    # ------------------------------------------------------
    # st.text_input은 문자열을 반환한다
    # 사용자가 입력한 값은 매 Rerun마다 다시 계산된다
    # 따라서 필요하다면 session_state에 저장해야 한다
    # ------------------------------------------------------
    
    st.markdown(
        """
        <h3 style="margin-bottom:6px;">
            학습 주제를 입력하세요 ✍🏻
        </h3>
        """,
        unsafe_allow_html=True
    )

    query = st.text_input(
        "학습 주제",
        placeholder="예 : Python 기초, LangChain 활용, FastAPI 개발 등",
        label_visibility="collapsed"
    )

    # ------------------------------------------------------
    # 2-2 버튼 클릭 감지
    # ------------------------------------------------------
    # st.button은 클릭 순간에만 True를 반환한다
    # Rerun 구조에서 이 조건은 "한 번만" 실행된다
    # ------------------------------------------------------
    
    if st.button("관련 영상 추천 받기 💌") :
        
        # --------------------------------------------------
        # 2-3 Spinner 사용 이유
        # --------------------------------------------------
        # Streamlit은 코드 실행이 끝난 후 화면을 그린다.
        # 일반적인 loading 플래그 방식은 중간 UI를 보여주기 어렵다.
        #
        # st.spinner는 내부 블록 실행 전에
        # 로딩 UI를 먼저 렌더링한다.
        # --------------------------------------------------
        
        with st.spinner("AI가 영상을 분석 중입니다...") :
            
            # --------------------------------------------------
            # 2-4 서비스 호출
            # --------------------------------------------------
            # UI는 데이터 소스를 모른다. 단지 결과를 받는다.
            # --------------------------------------------------
            
            result = fetch_recommend(query)
        
        # --------------------------------------------------
        # 2-5 반환 구조 처리
        # --------------------------------------------------
        # result는 항상 다음 구조를 가진다:
        #
        # {
        #     "data": {...} or None,
        #     "error": None or {...}
        # }
        #
        # 따라서 UI는 error 존재 여부만 판단하면 된다.
        # --------------------------------------------------
        
        if result["error"] :
            
            # 실패 시
            # --------------------------------------------------
            # 1. 기존 영상 데이터 제거 (상태 정합성 유지)
            # 2. 에러 메시지 저장
            # --------------------------------------------------
            st.session_state.videos = []
            st.session_state.error = result["error"]["message"]
        
        else :
            
            # 성공 시
            # --------------------------------------------------
            # 1. 에러 초기화
            # 2. 영상 목록 저장
            # --------------------------------------------------
            st.session_state.error = None
            st.session_state.videos = result["data"]["videos"]
            
            # 검색어 저장
            st.session_state.search_query = query
            
            # --------------------------------------------------
            # 추천 직후 첫 번째 영상 자동 선택
            # --------------------------------------------------
            # 왜 여기서 하는가?
            # 추천 결과가 확정된 직후이기 때문이다.
            # UI는 rerun 후 이 selected_video_id를 읽어
            # summary 패널을 자동으로 렌더링하게 된다.
            # --------------------------------------------------
            
            if result["data"]["videos"] :
                st.session_state.selected_video_id = result["data"]["videos"][0]["id"]
                st.session_state.summary = None
                st.session_state.timeline = []